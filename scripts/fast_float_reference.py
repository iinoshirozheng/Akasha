"""Reproduce fast-float2 F64 fixtures and source tables; Rust is test-only."""
from collections import Counter
from pathlib import Path
import hashlib
import json
import random
import re
import shutil
import subprocess
import tarfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'tests/fixtures/fast-float'
TABLES = ROOT / 'src/akasha/document/fast_float_tables.mojo'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def tables(source):
    """Copy literal tables, including original order; do not recompute powers."""
    def array(path, name):
        text = (source/path).read_text()
        match = re.search(r'const ' + name + r':[^=]+?=\s*\[(.*?)\];', text, re.S)
        assert match, (path, name)
        return match[1]

    pairs = re.findall(r'\((0x[0-9a-fA-F_]+),\s*(0x[0-9a-fA-F_]+)\)', array('src/table.rs', 'POWER_OF_FIVE_128'))
    assert len(pairs) == 651
    data = [('powers_of_five', 'UInt64', [v for pair in pairs for v in pair])]
    for name, target, dtype, size in [('TABLE', 'decimal_shift', 'UInt16', 65), ('TABLE_POW5', 'decimal_pow5', 'UInt8', 1308)]:
        values = re.findall(r'0x[0-9a-fA-F_]+|\d+', array('src/decimal.rs', name))
        assert len(values) == size
        data.append((target, dtype, values))
    ints = re.findall(r'\d+', array('src/number.rs', 'INT_POW10'))
    assert len(ints) == 16
    data.append(('int_pow10', 'UInt64', ints))
    f64_source = (source/'src/float.rs').read_text().split('impl Float for f64')[1]
    float_values = re.search(r'const TABLE:[^=]+?=\s*\[(.*?)\];', f64_source, re.S)[1]
    floats = [v.strip() for v in float_values.split(',') if v.strip()]
    assert len(floats) == 32
    data.append(('float_pow10', 'Float64', ['0.0' if v == '0.' else v for v in floats]))
    shifts = re.findall(r'\d+', array('src/simple.rs', 'POWERS'))
    assert len(shifts) == 19
    data.append(('binary_shifts', 'Int', shifts))
    lines = ['"""fast-float2 0.2.3 source tables (MIT); generated by scripts/fast_float_reference.py."""', '']
    for name, dtype, values in data:
        lines += ['', f'def {name}() -> Array[{dtype}, {len(values)}]:', f'    var result = Array[{dtype}, {len(values)}](fill=0)']
        lines += [f'    result[{i}] = {v}' for i, v in enumerate(values)]
        lines += ['    return result^']
    TABLES.write_text('\n'.join(lines) + '\n')


def exact_binary_decimal(n, exponent):
    if exponent >= 0:
        return str(n << exponent)
    scale = -exponent
    digits = str(n * 5**scale).zfill(scale + 1)
    return digits[:-scale] + '.' + digits[-scale:]


def inputs(source):
    cases = dict.fromkeys(bytes.fromhex(v['hex']) for v in json.loads((ROOT/'tests/fixtures/lance-json/contracts.json').read_text())['cases'])
    def add(value):
        cases[value.encode() if isinstance(value, str) else value] = None
    # Upstream regression inputs, including long literals; expectations still
    # come exclusively from the compiled source, not these test's annotations.
    for path in sorted((source/'tests').glob('*.rs')):
        for text in re.findall(r'"([+\-0-9.eE]+)"', path.read_text()):
            add(text)
    for q in range(-350, 318):
        for m in ('1', '9007199254740991', '18446744073709551615', '9999999999999999999'):
            add(f'{m}e{q}')
            add(f'-{m}e{q}')
    rng = random.Random(1030316)
    # Exact midpoints and one final decimal unit on both sides, with even and
    # odd significands, normal/subnormal boundaries, overflow and signed forms.
    for n, e in [(1, -1075), (3, -1075), (2**53-1, -1075), (2**54-1, 970)] + [(2*rng.randrange(2**52, 2**53)+1, rng.randrange(-1075, 970)) for _ in range(128)]:
        text = exact_binary_decimal(n, e)
        scale = len(text.split('.')[1]) if '.' in text else 0
        unscaled = int(text.replace('.', ''))
        for delta in (-1, 0, 1):
            digits = str(unscaled+delta).zfill(scale+1)
            value = digits[:-scale]+'.'+digits[-scale:] if scale else digits
            add(value)
            add('-'+value)
    midpoint = exact_binary_decimal(2**53+1, -53)
    for length in (767, 768, 769, 1024, 2000):
        add(midpoint + '0'*length + '1')
        add('-'+midpoint + '0'*length + '1')
        add('0.'+'0'*length+'1e'+str(length))
        add('1'+'0'*length+'e-'+str(length))
    for _ in range(2048):
        n = rng.randrange(1, 90)
        digits = ''.join(str(rng.randrange(10)) for _ in range(n))
        point = rng.randrange(n+1)
        add(rng.choice(('', '-', '+'))+digits[:point]+'.'+digits[point:]+rng.choice(('e', 'E'))+str(rng.randrange(-1200, 1200)))
    for text in ('', '.', '+', '-', '+.', '-.', '1e', '1e+', '1e-', '.1', '1.', '1.e2', '0x12', '01', '1_0', 'inf', 'infinity', 'nan', 'NaN', 'INFINITY', 'iNfInItY', 'nan(payload)', '1e9999999999999999', '0e99999999999999'):
        for prefix in ('', '+', '-', ' ', '\t'):
            for suffix in ('', 'x', '\0', ' ', 'E+'):
                add(prefix+text+suffix)
    for byte in range(256):
        add(bytes([byte]))
        add(b'1.25e2'+bytes([byte]))
        add(bytes([byte])+b'1.25')
    return list(cases)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    build = ROOT/'.build/fast-float-reference'
    (build/'src').mkdir(parents=True, exist_ok=True)
    meta = json.loads((ROOT/'tests/fixtures/lance-json/sources.json').read_text())
    dep = next(d for d in meta['dependencies'] if d['name'] == 'fast-float2')
    source = next((Path.home()/'.cargo/registry/src').glob('*/fast-float2-0.2.3'))
    archive = Path.home()/'.cargo/registry/cache'/source.parent.name/'fast-float2-0.2.3.crate'
    assert sha(archive) == dep['checksum']
    files = []
    with tarfile.open(archive) as tar:
        for path in sorted(source.rglob('*')):
            if path.is_file() and (path.suffix == '.rs' or path.name in ('LICENSE-MIT', 'LICENSE-APACHE', 'Cargo.toml')):
                relative = str(path.relative_to(source))
                assert path.read_bytes() == tar.extractfile('fast-float2-0.2.3/'+relative).read()
                files.append(dict(path=relative, sha256=sha(path)))
    dep = dict(dep, files=files)
    manifest = '[package]\nname="akasha-fast-float-reference"\nversion="0.1.0"\nedition="2024"\n[dependencies]\nfast-float2="=0.2.3"\n[workspace]\n'
    (build/'Cargo.toml').write_text(manifest)
    for path in (source/'src').glob('*.rs'):
        if path.name != 'lib.rs':
            shutil.copyfile(path, build/'src'/path.name)
    shutil.copyfile(ROOT/'scripts/fast_float_reference.rs', build/'src/main.rs')
    if (OUT/'Cargo.lock').exists():
        shutil.copyfile(OUT/'Cargo.lock', build/'Cargo.lock')
    subprocess.run(['cargo', 'fetch', *(['--locked'] if (OUT/'Cargo.lock').exists() else []), '--manifest-path', str(build/'Cargo.toml')], check=True)
    lock = tomllib.loads((build/'Cargo.lock').read_text())
    assert next(p for p in lock['package'] if p['name'] == 'fast-float2')['checksum'] == dep['checksum']
    values = inputs(source)
    output = subprocess.check_output(['cargo', 'run', '--quiet', '--release', '--locked', '--manifest-path', str(build/'Cargo.toml')], input=('\n'.join(v.hex() for v in values)+'\n').encode()).decode().splitlines()
    assert len(output) == len(values)
    rows = []
    for value, line in zip(values, output):
        full, partial, consumed, path, forced = line.split('\t')
        rows.append(dict(hex=value.hex(), full=full, partial=partial, consumed=int(consumed), path=path, long=forced))
    (OUT/'cases.json').write_text(json.dumps(rows, separators=(',', ':'))+'\n')
    shutil.copyfile(build/'Cargo.lock', OUT/'Cargo.lock')
    shutil.copyfile(source/'LICENSE-MIT', ROOT/'docs/upstream/licenses/fast-float2-MIT.txt')
    tables(source)
    counts = dict(Counter(row['path'] for row in rows))
    metadata = dict(dependencies=[dep], profile='f64; default std; copied internal modules unchanged; public crate result cross-check', generator_sha256=sha(__file__), scaffold_sha256=sha(ROOT/'scripts/fast_float_reference.rs'), input_fixture_sha256=sha(ROOT/'tests/fixtures/lance-json/contracts.json'), fixture_sha256=sha(OUT/'cases.json'), lock_sha256=sha(OUT/'Cargo.lock'), tables_sha256=sha(TABLES), counts=counts)
    (OUT/'sources.json').write_text(json.dumps(metadata, indent=2)+'\n')
    print(len(rows), counts)


if __name__ == '__main__':
    main()
